#!/usr/bin/env node
/**
 * Regenerates api/stateless/lib/coastline-data.ts, the coastline used to tell
 * whether a point is far inland (see api/stateless/lib/coast.ts).
 *
 * Source: Natural Earth 1:10m land (public domain, https://www.naturalearthdata.com).
 *
 * Only land polygons that lie wholly inside the south-west Pacific region below are
 * kept. Continents that reach outside it (Eurasia, Antarctica, ...) are left out, which
 * is deliberate: a point that is not inside a kept polygon is treated as "not known to be
 * inland", so the tides view still shows. Coordinates are rounded and the rings are
 * simplified to SIMPLIFY_DEGREES, far finer than the kilometres the inland check works in.
 *
 * Usage: node scripts/build-coastline.mjs [path/to/ne_10m_land.geojson]
 *        (downloads the file when no path is given)
 */
import fs from 'node:fs';

const SOURCE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_10m_land.geojson';
const OUTPUT = new URL('../api/stateless/lib/coastline-data.ts', import.meta.url);

// A polygon is kept when its whole bounding box is inside one of these
const REGIONS = [
    { west: 90, east: 180, south: -62, north: 12 },
    { west: -180, east: -100, south: -62, north: 12 },
];
const SIMPLIFY_DEGREES = 0.001; // about 100 m
const DECIMALS = 4;

function inRegion(box) {
    return REGIONS.some((r) => box.west >= r.west && box.east <= r.east && box.south >= r.south && box.north <= r.north);
}

function bbox(ring) {
    const box = { west: Infinity, east: -Infinity, south: Infinity, north: -Infinity };
    for (const [x, y] of ring) {
        box.west = Math.min(box.west, x);
        box.east = Math.max(box.east, x);
        box.south = Math.min(box.south, y);
        box.north = Math.max(box.north, y);
    }
    return box;
}

// Distance from p to the segment a-b, in degrees (the tolerance is far too small for the
// latitude scaling to matter)
function segmentDistance(p, a, b) {
    const dx = b[0] - a[0];
    const dy = b[1] - a[1];
    const len = dx * dx + dy * dy;
    let t = len === 0 ? 0 : ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / len;
    t = Math.max(0, Math.min(1, t));
    return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy));
}

// Douglas-Peucker, iterative so that a ring of 100k points cannot overflow the stack
function simplify(points, tolerance) {
    const keep = new Uint8Array(points.length);
    keep[0] = 1;
    keep[points.length - 1] = 1;
    const stack = [[0, points.length - 1]];
    while (stack.length) {
        const [first, last] = stack.pop();
        let max = 0;
        let index = -1;
        for (let i = first + 1; i < last; i++) {
            const d = segmentDistance(points[i], points[first], points[last]);
            if (d > max) {
                max = d;
                index = i;
            }
        }
        if (index !== -1 && max > tolerance) {
            keep[index] = 1;
            stack.push([first, index], [index, last]);
        }
    }
    return points.filter((_, i) => keep[i]);
}

function prepare(ring) {
    const rounded = [];
    for (const [x, y] of ring) {
        const point = [Number(x.toFixed(DECIMALS)), Number(y.toFixed(DECIMALS))];
        const last = rounded[rounded.length - 1];
        if (!last || last[0] !== point[0] || last[1] !== point[1]) rounded.push(point);
    }
    const simple = simplify(rounded, SIMPLIFY_DEGREES);
    // A ring needs a closing point and at least three distinct ones
    return simple.length >= 4 ? simple : null;
}

const path = process.argv[2];
const text = path
    ? fs.readFileSync(path, 'utf8')
    : await (await fetch(SOURCE)).text();
const land = JSON.parse(text);

const polygons = [];
let seen = 0;

for (const feature of land.features) {
    const geometry = feature.geometry;
    const parts = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates;
    for (const part of parts) {
        seen++;
        if (!inRegion(bbox(part[0]))) continue;
        const rings = part.map(prepare).filter(Boolean);
        // The first ring is the outline; a polygon whose outline vanished is dropped with its holes
        if (!rings.length || !prepare(part[0])) continue;
        polygons.push(rings);
    }
}

const flat = polygons.map((rings) => rings.map((ring) => ring.flatMap(([x, y]) => [x, y])));

const body = `/* eslint-disable */
/**
 * Generated by scripts/build-coastline.mjs - do not edit by hand.
 *
 * Land polygons of the south-west Pacific and Australia from Natural Earth
 * (1:10m land, public domain, https://www.naturalearthdata.com), simplified to about
 * 100 m. Each polygon is a list of rings (outline first, then holes) and each ring a flat
 * [longitude, latitude, longitude, latitude, ...] list.
 */
export const COASTLINE: number[][][] = ${JSON.stringify(flat)};
`;

fs.writeFileSync(OUTPUT, body);

const points = flat.reduce((sum, rings) => sum + rings.reduce((s, r) => s + r.length / 2, 0), 0);
console.log(`kept ${polygons.length} of ${seen} polygons, ${points} points, ${(body.length / 1024).toFixed(0)} KiB -> api/stateless/lib/coastline-data.ts`);
